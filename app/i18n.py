def translate(key: str, lang: str = "ar", **kwargs) -> str:
    entry = T.get(key)
    if entry is None:
        return key
    text = entry.get(lang) or entry.get("ar") or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
